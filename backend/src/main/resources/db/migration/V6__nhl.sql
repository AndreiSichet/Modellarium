-- The NHL, the fifth league to share this schema and the second that is not
-- basketball.
--
-- Its own prediction table, for the reason V2, V3 and V4 give: two markets
-- against the NBA's seven would mean five always-null columns and nothing in
-- the row saying which league it was. The `game` table IS reused, which is
-- safe because the five leagues' team-id ranges are disjoint - the NBA's
-- 1610612737-1610612766, the WNBA's 1611661313-1611661332, the G League's
-- 1612709889 upward, the NFL's 1613000001-1613000032 and the NHL's
-- 1614000001-1614000033 - and TeamSeeder asserts all ten pairs at startup
-- rather than assuming it.
--
-- THE NHL'S IDS ARE PROJECT-ASSIGNED, like the NFL's and unlike the three
-- nba_api leagues'. Phase 1 authored the range in nhl_franchises.py and chose
-- it to sit clear of the four already in use.
--
-- TWO MARKETS, NOT THREE, AND THE MISSING ONE IS A DECISION. Totals are NOT
-- SERVED for the NHL: a constant predictor beat the fitted model on test
-- (MAE 1.833916 against 1.847400), so there is no totals column here at all.
-- A nullable column would have invited someone to fill it later without
-- re-reading why it is empty. `/health` declares the refusal with the code
-- `no_skill_over_constant`, which is where that fact belongs.
--
-- WHAT IS STORED AND WHAT IS NOT. The two market values, the cutoff and the
-- staleness are per-row facts and are stored. The winner's CAVEAT, the
-- puck-line definition and the source attribution are identical on every row
-- this table will ever hold, so by the rule in CLAUDE.md section 8 they are
-- constants about which model produced a number and are attached at
-- response-build time instead.
--
-- NO `week` ANALOGUE. The NFL stores `week` because an NFL result is
-- discussed by week and the model reads it as a feature. The NHL has no such
-- unit - its season is a date line - and the season label is recoverable from
-- game.game_date, so nothing is duplicated here.
--
-- The nullability pattern follows the entity, as V1's did: a NOT NULL column
-- is a Java primitive and a nullable one is an object type.

CREATE TABLE nhl_prediction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    game_id BIGINT,
    home_win_probability DOUBLE PRECISION NOT NULL,
    home_wins_by_two_or_more DOUBLE PRECISION NOT NULL,
    data_as_of DATE,
    stale BOOLEAN NOT NULL,
    predicted_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_nhl_prediction PRIMARY KEY (id)
);

ALTER TABLE nhl_prediction
    ADD CONSTRAINT fk_nhl_prediction_game
    FOREIGN KEY (game_id) REFERENCES game (id);
